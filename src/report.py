"""Writes reports/REPORT.md from the run's results, so every number in it matches the model."""
from pathlib import Path

import pandas as pd


def _table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(f"{v:,}" if isinstance(v, (int, float)) and abs(v) >= 1000 else str(v)
                                       for v in r.values) + " |")
    return "\n".join(lines)


def write_report(res: dict, comparison: pd.DataFrame, importance: pd.DataFrame, odds: pd.DataFrame,
                 top_risk: pd.DataFrame, out: Path) -> None:
    t = res["test"]
    a = res["assumptions"]
    p, d = t["profit_threshold"], t["default_0.5"]
    everyone, random_net = t["target_everyone"], t["random_same_size_net_profit"]
    seg = res["churn_rate_by_segment"]
    reach = p["churners_reached"] / max(p["churners_total"], 1)
    if p["threshold"] < 0.5:
        threshold_note = (f"The threshold is below 0.5 because the costs are lopsided: missing a churner loses "
                          f"months of revenue, while a wasted offer costs ${a['offer_cost']:.0f}.")
    else:
        threshold_note = ("The threshold is at or above 0.5 because, under these assumptions, offers sent to "
                          "lower-risk customers cost more than the revenue they save.")
    gap = p["net_profit"] - d["net_profit"]
    threshold_note += (f" On the test set it earned ${abs(gap):,.0f} {'more' if gap >= 0 else 'less'} than the default "
                       f"0.5 cut-off. The threshold was chosen on training data, so small differences on new data "
                       f"are expected; the profit curve is flat near its peak.")

    md = f"""# Churn model: results and business impact

_Generated by `python -m src.train`. Every number below comes from that run._

## Summary

- **Model:** {res['best_model']}, chosen by PR-AUC in 5-fold cross-validation.
- **Test set performance:** PR-AUC **{t['pr_auc']}**, ROC-AUC **{t['roc_auc']}** (a no-skill model scores {res['data']['churn_rate']:.2f} PR-AUC and 0.50 ROC-AUC).
- **Recommended action:** offer the retention deal to customers with a churn score of **{p['threshold']}** or higher. On the held-out test set that means **{p['customers_targeted']:,} offers**, reaching **{p['churners_reached']:,} of {p['churners_total']:,} churners ({reach:.0%})**, for an estimated **net gain of ${p['net_profit']:,.0f}**.

| Strategy (test set, {everyone['customers_targeted']:,} customers) | Offers sent | Churners reached | Net profit |
|---|---|---|---|
| Model, profit-optimized threshold ({p['threshold']}) | {p['customers_targeted']:,} | {p['churners_reached']:,} | **${p['net_profit']:,.0f}** |
| Model, default threshold (0.5) | {d['customers_targeted']:,} | {d['churners_reached']:,} | ${d['net_profit']:,.0f} |
| Random customers, same number of offers | {p['customers_targeted']:,} | — | ${random_net:,.0f} |
| Offer to everyone | {everyone['customers_targeted']:,} | {everyone['churners_reached']:,} | ${everyone['net_profit']:,.0f} |

**Assumptions** (change them with command-line flags): each offer costs **${a['offer_cost']:.0f}**; it keeps **{a['save_rate']:.0%}** of customers who would otherwise leave; a saved customer is worth **{a['months_retained']} months** of their current monthly charge. The threshold was chosen on cross-validated training predictions, so the test set played no part in any decision.

![Profit curve](figures/03_profit_curve.png)

## Who churns

![Churn by segment](figures/01_churn_by_segment.png)

- Contract: {', '.join(f'{k} {v}%' for k, v in seg['Contract'].items())}
- Tenure: {', '.join(f'{k} {v}%' for k, v in seg['TenureBand'].items())}
- Internet service: {', '.join(f'{k} {v}%' for k, v in seg['InternetService'].items())}

## Model comparison (5-fold cross-validation, training set)

{_table(comparison[['model', 'PR-AUC', 'PR-AUC sd', 'ROC-AUC', 'Recall', 'Precision', 'F1']])}

PR-AUC is the main metric. Only about a quarter of customers churn, and PR-AUC measures how well the model finds them without flooding the team with false alarms. Accuracy would be misleading: predicting "no one churns" is already about 74% accurate.

![ROC and PR curves](figures/02_roc_pr_curves.png)

## What drives the predictions

![Feature importance](figures/04_feature_importance.png)

Logistic regression odds ratios (above 1 raises churn odds, below 1 lowers them; one-hot categories are relative to the dropped level):

{_table(odds)}

Read these together, not one at a time. Overlapping features share credit: monthly charges rise with fiber internet and add-on services, so once those are in the model, monthly charges can even show a reversed sign. Permutation importance (chart above) is the better guide to what matters overall.

These are associations, not proof of cause. Month-to-month customers churn more, but that doesn't prove a contract would keep any given customer.

## Errors at the chosen threshold

![Confusion matrix](figures/05_confusion_matrix.png)

At threshold {p['threshold']}: recall {t['profit_threshold']['recall']}, precision {t['profit_threshold']['precision']}. {threshold_note}

## Who to call first (top 10 by revenue at risk, test set)

{_table(top_risk)}

Full list: `reports/top_at_risk_customers.csv`.

## Limitations

- **Single snapshot.** The data doesn't say *when* customers churned, so this ranks risk, not timing.
- **Business assumptions.** Offer cost, save rate and value horizon are estimates; the profit curve shows how sensitive the result is. A real deployment would A/B test the offer to measure the true save rate.
- **Sample dataset.** IBM's Telco data is a teaching sample, so this demonstrates method, not a real company's numbers.
"""
    out.write_text(md, encoding="utf-8")
